"""scene_layout.py の配置から vlm_pick_place/worlds/vlm_table.sdf を生成する.

評価用の vlm_table_eval.sdf も作る（動画用の斜めカメラを省き、CPU 描画の負荷を減らす.
物体の配置は評価ノードがエピソードごとに入れ替える）.

  python tools/make_world.py
"""

import math
import os

from scene_layout import (CAMERA_HFOV_DEG, CAMERA_SIZE, CAMERA_XYZ, COLORS, CUBE_SIZE, CUBES,
                          SIDE_CAMERA_HFOV_DEG, SIDE_CAMERA_LOOK_AT, SIDE_CAMERA_XYZ, TABLE_Z,
                          TRAY_INNER, TRAY_SIZE, TRAY_THICK, TRAYS, polar_to_xy)

WORLDS = os.path.join(os.path.dirname(__file__), '..', 'vlm_pick_place', 'worlds')


def rgba(rgb):
    return ' '.join(f'{v:.2f}' for v in rgb) + ' 1'


def cube(color, r, deg):
    x, y = polar_to_xy(r, deg)
    c, s = rgba(COLORS[color]), CUBE_SIZE
    return f"""
    <model name="{color}_cube">
      <pose>{x:.4f} {y:.4f} {TABLE_Z + s / 2:.4f} 0 0 0</pose>
      <link name="link">
        <inertial>
          <mass>0.05</mass>
          <inertia><ixx>0.00002</ixx><iyy>0.00002</iyy><izz>0.00002</izz></inertia>
        </inertial>
        <collision name="collision">
          <geometry><box><size>{s} {s} {s}</size></box></geometry>
          <surface><friction><ode><mu>0.9</mu><mu2>0.9</mu2></ode></friction></surface>
        </collision>
        <visual name="visual">
          <geometry><box><size>{s} {s} {s}</size></box></geometry>
          <material><ambient>{c}</ambient><diffuse>{c}</diffuse></material>
        </visual>
      </link>
    </model>"""


def tray(color, r, deg):
    x, y = polar_to_xy(r, deg)
    inner = rgba(tuple(v * 0.7 + 0.15 for v in COLORS[color]))
    t = TRAY_THICK
    return f"""
    <model name="{color}_tray">
      <static>true</static>
      <pose>{x:.4f} {y:.4f} {TABLE_Z + t / 2:.4f} 0 0 {math.radians(deg):.4f}</pose>
      <link name="link">
        <collision name="collision">
          <geometry><box><size>{TRAY_SIZE} {TRAY_SIZE} {t}</size></box></geometry>
        </collision>
        <visual name="rim">
          <geometry><box><size>{TRAY_SIZE} {TRAY_SIZE} {t}</size></box></geometry>
          <material><ambient>0.95 0.95 0.95 1</ambient><diffuse>0.95 0.95 0.95 1</diffuse></material>
        </visual>
        <visual name="inner">
          <pose>0 0 {t / 2 + 0.0005:.4f} 0 0 0</pose>
          <geometry><box><size>{TRAY_INNER} {TRAY_INNER} 0.001</size></box></geometry>
          <material><ambient>{inner}</ambient><diffuse>{inner}</diffuse></material>
        </visual>
      </link>
    </model>"""


def camera():
    """真下を向いたカメラセンサー.

    古い crane_plus（講義の Docker イメージ）にはカメラセンサーが無いので、URDF の
    camera_color_optical_frame と同じ位置・向きにワールド側でセンサーを置く.
    Gazebo のカメラは +X が視線、+Z が画像の上なので、pitch +90° で真下を向けると
    画像の右 = -Y, 画像の下 = -X となり、URDF の光学フレーム (rpy 0, pi, pi/2) と一致する.
    """
    x, y, z = CAMERA_XYZ
    w, h = CAMERA_SIZE
    return f"""
    <model name="overhead_camera">
      <static>true</static>
      <pose>{x} {y} {TABLE_Z + z:.4f} 0 1.5708 0</pose>
      <link name="link">
        <sensor name="camera" type="camera">
          <update_rate>10</update_rate>
          <always_on>true</always_on>
          <topic>image_raw</topic>
          <camera>
            <horizontal_fov>{math.radians(CAMERA_HFOV_DEG):.6f}</horizontal_fov>
            <image><width>{w}</width><height>{h}</height></image>
            <clip><near>0.05</near><far>10.0</far></clip>
          </camera>
        </sensor>
      </link>
    </model>"""


def side_camera():
    """動画撮影用の斜めカメラ. Gazebo のカメラは +X が視線なので、注視点へ向く yaw / pitch を求める."""
    (x, y, z), (tx, ty, tz) = SIDE_CAMERA_XYZ, SIDE_CAMERA_LOOK_AT
    dx, dy, dz = tx - x, ty - y, tz - z
    yaw = math.atan2(dy, dx)
    pitch = math.atan2(-dz, math.hypot(dx, dy))   # 正で下向き
    w, h = CAMERA_SIZE
    return f"""
    <model name="side_camera">
      <static>true</static>
      <pose>{x} {y} {TABLE_Z + z:.4f} 0 {pitch:.4f} {yaw:.4f}</pose>
      <link name="link">
        <sensor name="side_camera" type="camera">
          <update_rate>10</update_rate>
          <always_on>true</always_on>
          <topic>side_camera/image_raw</topic>
          <camera>
            <horizontal_fov>{math.radians(SIDE_CAMERA_HFOV_DEG):.6f}</horizontal_fov>
            <image><width>{w}</width><height>{h}</height></image>
            <clip><near>0.05</near><far>10.0</far></clip>
          </camera>
        </sensor>
      </link>
    </model>"""


HEADER = """<?xml version="1.0" ?>
<!-- generated by tools/make_world.py (編集はそちらで) -->
<sdf version="1.9">
  <world name="default">
    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="ignition-gazebo-physics-system" name="ignition::gazebo::systems::Physics"/>
    <plugin filename="ignition-gazebo-user-commands-system" name="ignition::gazebo::systems::UserCommands"/>
    <plugin filename="ignition-gazebo-scene-broadcaster-system" name="ignition::gazebo::systems::SceneBroadcaster"/>
    <plugin filename="ignition-gazebo-sensors-system" name="ignition::gazebo::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>

    <include><uri>https://fuel.ignitionrobotics.org/1.0/OpenRobotics/models/Sun</uri></include>
    <include><uri>https://fuel.ignitionrobotics.org/1.0/OpenRobotics/models/Ground%20Plane</uri></include>
    <include>
      <uri>https://fuel.ignitionrobotics.org/1.0/OpenRobotics/models/Table</uri>
      <pose>0.29 0 0 0 0 1.5708</pose>
    </include>
"""


def write(name, body):
    out = os.path.join(WORLDS, name)
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(HEADER + body + '\n  </world>\n</sdf>\n')
    print('wrote', os.path.normpath(out))


def main():
    objects = ''.join(tray(*t) for t in TRAYS) + ''.join(cube(*c) for c in CUBES)
    write('vlm_table.sdf', camera() + side_camera() + objects)
    write('vlm_table_eval.sdf', camera() + objects)


if __name__ == '__main__':
    main()
